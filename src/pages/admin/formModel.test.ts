import { describe, expect, it } from 'vitest'
import { buildSeedCatalog } from '../../data/seed'
import { buildSchema, fromFormValues, slugify, toFormValues } from './formModel'
import { newRecordDefaults, RESOURCE_BY_KEY } from './resources'

const catalog = buildSeedCatalog()
const lookups = { catalog, schools: [] }
const courses = RESOURCE_BY_KEY.get('courses')!
const admissions = RESOURCE_BY_KEY.get('admissions')!

describe('admin form model', () => {
  it('slugifies names into readable ids', () => {
    expect(slugify('Fine & Applied Arts')).toBe('fine-applied-arts')
    expect(slugify('  Électrical  ')).toBe('electrical')
  })

  it('round-trips a course, including list fields and links', () => {
    const row = catalog.courses.find((c) => c.id === 'law')! as unknown as Record<string, unknown>
    const values = toFormValues(courses, row, lookups)
    expect(values.what_you_learn).toContain('\n')
    expect(values.careers).toContain('lawyer')
    const { row: out, links } = fromFormValues(courses, values, false)
    expect(out.what_you_learn).toEqual(row.what_you_learn)
    expect(out).not.toHaveProperty('id') // IDs can't be changed on edit
    expect(links.find((l) => l.table === 'course_careers')?.ids).toContain('lawyer')
  })

  it('creates an id from the name for new slug records', () => {
    const values = { ...toFormValues(courses, newRecordDefaults(courses), lookups), name: 'Marine Biology', category_id: 'agriculture' }
    expect(fromFormValues(courses, values, true).row.id).toBe('marine-biology')
  })

  it('converts blank optional fields to null', () => {
    const values = toFormValues(admissions, newRecordDefaults(admissions), lookups)
    const { row } = fromFormValues(admissions, { ...values, course_id: 'law' }, true)
    expect(row.institution_id).toBeNull()
    expect(row.utme_subjects).toEqual([])
    expect(row).not.toHaveProperty('id') // generated by the database
  })

  it('refuses "verified" without a source and a date', () => {
    const schema = buildSchema(admissions)
    const values = { ...toFormValues(admissions, newRecordDefaults(admissions), lookups), course_id: 'law', verification_status: 'verified' }
    const result = schema.safeParse(values)
    expect(result.success).toBe(false)
    expect(result.error!.issues.map((i) => i.path[0]).sort()).toEqual(['last_verified_at', 'source_id'])
    expect(schema.safeParse({ ...values, source_id: 'jamb-ibass', last_verified_at: '2026-10-23' }).success).toBe(true)
  })

  it('validates required fields and id format', () => {
    const schema = buildSchema(courses)
    const result = schema.safeParse({ ...toFormValues(courses, newRecordDefaults(courses), lookups), id: 'Bad ID!' })
    expect(result.success).toBe(false)
    const paths = result.error!.issues.map((i) => i.path[0])
    expect(paths).toEqual(expect.arrayContaining(['id', 'name', 'category_id', 'summary']))
  })
})
