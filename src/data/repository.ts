import { isDemoMode } from '../lib/config'
import type { Catalog, SchoolEnquiry, SchoolRole, UsageEventType } from './types'

// The app talks to data only through this interface. There are two
// implementations: Supabase (live) and an in-memory store (demo mode).

export type TableName =
  | 'career_categories'
  | 'subject_pathways'
  | 'courses'
  | 'careers'
  | 'course_pathways'
  | 'course_careers'
  | 'institutions'
  | 'institution_programmes'
  | 'educational_sources'
  | 'admission_requirements'
  | 'verification_records'
  | 'quiz_questions'
  | 'quiz_options'
  | 'school_enquiries'
  | 'schools'
  | 'school_memberships'
  | 'subscriptions'
  | 'sponsorships'
  | 'profiles'

export type Row = Record<string, unknown>

/** Which database table holds each part of the catalog. */
export const CATALOG_TABLES: Record<keyof Catalog, TableName> = {
  categories: 'career_categories',
  pathways: 'subject_pathways',
  courses: 'courses',
  careers: 'careers',
  coursePathways: 'course_pathways',
  courseCareers: 'course_careers',
  institutions: 'institutions',
  programmes: 'institution_programmes',
  sources: 'educational_sources',
  admissions: 'admission_requirements',
  quizQuestions: 'quiz_questions',
  quizOptions: 'quiz_options',
}

/** Tables whose ids are generated by the database (uuid). Others use readable slugs. */
export const GENERATED_ID_TABLES: TableName[] = [
  'institution_programmes',
  'admission_requirements',
  'verification_records',
  'school_enquiries',
  'schools',
  'school_memberships',
  'subscriptions',
  'sponsorships',
]

export interface UsageSummaryRow {
  event_type: string
  total: number
  last_30_days: number
}

export interface SchoolSummaryRow {
  event_type: string
  school_level: string | null
  category_id: string | null
  total: number
}

export type EnquiryInput = Pick<
  SchoolEnquiry,
  'school_name' | 'contact_name' | 'role_title' | 'email' | 'phone' | 'state' | 'student_count' | 'message'
> & { consent: true }

export interface ListOptions {
  order?: string
  ascending?: boolean
  eq?: Record<string, string>
}

export interface Repository {
  readonly mode: 'demo' | 'live'
  loadCatalog(): Promise<Catalog>
  list(table: TableName, options?: ListOptions): Promise<Row[]>
  insert(table: TableName, row: Row): Promise<Row>
  update(table: TableName, id: string, patch: Row): Promise<Row>
  remove(table: TableName, id: string): Promise<void>
  /** Replaces all links from one course to pathways or careers. */
  setCourseLinks(table: 'course_pathways' | 'course_careers', courseId: string, ids: string[]): Promise<void>
  submitEnquiry(input: EnquiryInput): Promise<void>
  recordUsage(event: UsageEventType, schoolLevel: string | null, categoryId: string | null, schoolCode: string | null): Promise<void>
  lookupSchoolCode(code: string): Promise<string | null>
  usageSummary(): Promise<UsageSummaryRow[]>
  schoolSummary(schoolId: string): Promise<SchoolSummaryRow[]>
  addSchoolMember(schoolId: string, email: string, role: SchoolRole): Promise<void>
}

let instance: Promise<Repository> | null = null

/** Loads the right implementation once. Each is a separate bundle chunk. */
export function getRepository(): Promise<Repository> {
  instance ??= isDemoMode
    ? import('./demoRepository').then((m) => m.createDemoRepository())
    : import('./supabaseRepository').then((m) => m.createSupabaseRepository())
  return instance
}
